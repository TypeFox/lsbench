// generates src/version.ts from package.json so the CLI version stays in sync
// with the published package version without hand-editing two places.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));

const contents = `// generated by scripts/gen-version.mjs — do not edit.
export const CLI_VERSION = '${pkg.version}';
`;

const target = new URL('src/version.ts', root);
writeFileSync(target, contents);

console.log(`wrote ${fileURLToPath(target)} (CLI_VERSION=${pkg.version})`);
